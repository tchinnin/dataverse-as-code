#!/usr/bin/env python3
"""
dv_metadata_docs.py — documentation of the Dataverse metadata model
===================================================================

Generates a Mermaid entity relationship diagram from the ``*.dv.metadata.yaml``
model (see the dvac-metadata skill)::

    erd <model-dir> [--out <file>] [--check] [--format markdown|mermaid]
                    [--tables <a,b>] [--no-columns] [--lang <LCID>]

Offline and read-only: reads the model files only, never the environment. The
model is validated first (the dvac-metadata validator); an invalid model is
refused. The output is deterministic — same model, same bytes — so the file can
be committed and checked in CI with ``--check``.

Exit codes:
    0  success (or --check: the file is up to date)
    1  error, invalid model, or --check: the file is missing or stale

Do not edit this script per project — edit the model files.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

SKILL_DIR = Path(__file__).resolve().parent.parent
# The model loader and validator belong to the sibling skill of the same plugin.
sys.path.insert(0, str(SKILL_DIR.parent / "dvac-metadata" / "scripts"))
import dv_metadata as dvm  # noqa: E402

GENERATED = "<!-- Generated by dv_metadata_docs.py from the *.dv.metadata.yaml model. Do not edit by hand. -->"


# --------------------------------------------------------------------------- #
# Model
# --------------------------------------------------------------------------- #
def validated_model(model_arg):
    """Validated model, or SystemExit with the validation errors."""
    model_dir = dvm.find_model_dir(Path(model_arg))
    if model_dir is None:
        raise SystemExit(f"ERROR: no {dvm.META_FILE} found at or above {model_arg}")
    report = dvm.validate_model(model_dir)
    if report.errors:
        for e in report.errors:
            print("  ✗ " + e, file=sys.stderr)
        raise SystemExit(f"ERROR: the model is invalid ({len(report.errors)} error(s)) — "
                         "run dv_metadata.py validate and fix it first")
    meta, choices, tables = dvm.load_model(model_dir)
    return {"meta": meta, "choices": choices, "tables": tables}


def text(value, lcid, base):
    """Text of a localized value in the requested language, else the base language."""
    texts = value or {}
    return texts.get(lcid) or texts.get(base) or next(iter(texts.values()), "")


# --------------------------------------------------------------------------- #
# Mermaid
# --------------------------------------------------------------------------- #
def comment(s):
    """Mermaid ER comments are double-quoted and cannot contain a double quote."""
    return '"' + " ".join(str(s).replace('"', "'").split()) + '"'


def column_type(col):
    """Attribute type shown in the diagram: the model type, fx_<result> for a formula."""
    if col["type"] == "formula":
        return f"fx_{col['result_type']}"
    return col["type"]


def column_comment(col, choices, lcid, base):
    parts = [text(col.get("label"), lcid, base)]
    if col.get("primary"):
        parts.append("primary name")
    if col.get("required") or col.get("required_level") == "required":
        parts.append("required")
    if col.get("choice"):
        parts.append(f"choice {choices.get(col['choice'].lower(), col['choice'])}")
    return " · ".join(p for p in parts if p)


def build_erd(model, tables_filter=None, columns=True, lcid=None):
    """Mermaid erDiagram source for the model."""
    base = dvm.model_lcid(model["meta"])
    lcid = lcid or base
    # Names are case-insensitive in Dataverse; the diagram uses the model's spelling.
    tables = {t["key"].lower(): t for t in model["tables"]}
    choices = {name.lower(): name for name in model["choices"]}  # lower → model spelling

    def display(name):
        t = tables.get(name.lower())
        return t["key"] if t else name.lower()

    wanted = None
    if tables_filter:
        wanted = {n.lower() for n in tables_filter}
        unknown = sorted(wanted - set(tables))
        if unknown:
            raise SystemExit(f"ERROR: not in the model: {', '.join(unknown)}")

    selected = [tables[k] for k in sorted(tables) if wanted is None or k in wanted]
    lines = ["erDiagram"]
    for t in selected:
        key = t["key"]
        lines.append(f"    {key} {{")
        if columns:
            lines.append(f"        guid {key.lower()}id PK {comment(text(t.get('label'), lcid, base))}")
            key_columns = {c.lower() for k in t.get("keys") or [] for c in k["columns"]}
            cols = sorted((t.get("columns") or {}).items(), key=lambda kv: not kv[1].get("primary"))
            for cname, col in cols:
                marks = []
                if col["type"] == "lookup":
                    marks.append("FK")
                if cname.lower() in key_columns:
                    marks.append("UK")
                lines.append(f"        {column_type(col)} {cname}"
                             + (f" {', '.join(marks)}" if marks else "")
                             + f" {comment(column_comment(col, choices, lcid, base))}")
        lines.append("    }")

    rels = []
    for t in selected:
        for cname, col in (t.get("columns") or {}).items():
            if col["type"] != "lookup":
                continue
            required = col.get("required") or col.get("required_level") == "required"
            parent = "||" if required else "|o"
            cascade = dvm.cascade_label(dvm.expand_cascade(col["cascade"]))
            rels.append((t["key"].lower(), cname.lower(),
                         f"    {display(col['target'])} {parent}--o{{ {t['key']} : "
                         f"{comment(f'{cname} ({cascade})')}"))
    lines.extend(r[2] for r in sorted(rels))
    return "\n".join(lines) + "\n"


def render(model, fmt="markdown", **kwargs):
    erd = build_erd(model, **kwargs)
    if fmt == "mermaid":
        return erd
    return "\n".join([GENERATED, "", "# Entity relationship diagram", "",
                      "```mermaid", erd.rstrip("\n"), "```", ""])


# --------------------------------------------------------------------------- #
# CLI
# --------------------------------------------------------------------------- #
def write_or_check(content, out, check):
    """Shared by the documentation tools: print, write, or compare with the file."""
    if check:
        if not out:
            raise SystemExit("ERROR: --check needs --out <file>")
        path = Path(out)
        if not path.is_file() or path.read_text(encoding="utf-8") != content:
            print(f"STALE: {out} differs from the model — regenerate it", file=sys.stderr)
            return 1
        print(f"Up to date: {out}")
        return 0
    if out:
        path = Path(out)
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(content)
        print(f"Written: {out}")
    else:
        sys.stdout.write(content)
    return 0


def _csv(value):
    return [v.strip() for v in value.split(",") if v.strip()] if value else None


def cmd_erd(args):
    model = validated_model(args.model)
    content = render(model, fmt=args.format, tables_filter=_csv(args.tables),
                     columns=not args.no_columns, lcid=args.lang)
    return write_or_check(content, args.out, args.check)


def main(argv=None):
    ap = argparse.ArgumentParser(prog="dv_metadata_docs.py", description=__doc__.split("\n\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("erd", help="Mermaid entity relationship diagram of the model")
    p.add_argument("model", help="model dir (holds _meta.dv.metadata.yaml) or a path below it")
    p.add_argument("--out", help="write to this file instead of stdout")
    p.add_argument("--check", action="store_true", help="compare with --out instead of writing (CI)")
    p.add_argument("--format", choices=["markdown", "mermaid"], default="markdown",
                   help="markdown (default): a document with a mermaid block; mermaid: the bare diagram")
    p.add_argument("--tables", help="comma-separated table schema names to include (default: all)")
    p.add_argument("--no-columns", action="store_true", help="tables and relationships only")
    p.add_argument("--lang", type=int, help="LCID of the labels (default: the model's base language)")
    args = ap.parse_args(argv)
    return {"erd": cmd_erd}[args.cmd](args)


if __name__ == "__main__":
    sys.exit(main())
