#!/usr/bin/env python3
"""
dv_plugin_docs.py — documentation of the Dataverse plug-in registrations
========================================================================

Generates a Markdown document with Mermaid diagrams from every
``*.dv.plugin.yaml`` file below a path (see the dvac-plugins skill)::

    doc <path> [--out <file>] [--check] [--tables <a,b>]

The document has two sections:

    Execution pipeline  one diagram and one table per (table, message): the steps
                        in the order Dataverse runs them — stage, then mode, then
                        rank — around the main operation.
    Custom APIs         a diagram of the bound tables, APIs and plug-in classes,
                        then the signature of each API.

Offline and read-only: reads the model files only, never the environment. The
model is validated first (the dvac-plugins validator); an invalid model is
refused. The output is deterministic — same model, same bytes — so the file can
be committed and checked in CI with ``--check``.

Exit codes:
    0  success (or --check: the file is up to date)
    1  error, invalid model, or --check: the file is missing or stale

Do not edit this script per project — edit the model files.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

SKILL_DIR = Path(__file__).resolve().parent.parent
# The model loader and validator belong to the sibling skill of the same plugin.
sys.path.insert(0, str(SKILL_DIR.parent / "dvac-plugins" / "scripts"))
import dv_plugin as dvp  # noqa: E402

GENERATED = "<!-- Generated by dv_plugin_docs.py from the *.dv.plugin.yaml files. Do not edit by hand. -->"

STAGE_ORDER = {"pre-validation": 10, "pre-operation": 20, "post-operation": 40}
STAGE_TITLE = {"pre-validation": "Pre-validation", "pre-operation": "Pre-operation",
               "post-operation": "Post-operation"}
NO_TABLE = "(any table)"


# --------------------------------------------------------------------------- #
# Model
# --------------------------------------------------------------------------- #
def load_units(path_arg):
    """Validated units, or SystemExit with the validation errors."""
    path = Path(path_arg)
    report = dvp.validate_path(path)
    if report.errors:
        for e in report.errors:
            print("  ✗ " + e, file=sys.stderr)
        raise SystemExit(f"ERROR: the model is invalid ({len(report.errors)} error(s)) — "
                         "run dv_plugin.py validate and fix it first")
    files = dvp.find_files(path)
    roots = [dvp.find_repo_root(files[0].parent), path.resolve() if path.is_dir() else path.resolve().parent]
    units = []
    for f in files:
        data = dvp.load_yaml(f)
        kind = dvp.unit_kind(data)
        units.append({
            "file": source_path(f, roots), "kind": kind, "name": data[kind]["name"],
            "steps": [dvp.desired_step(s) for s in data.get("steps") or []],
            "custom_apis": {k: dvp.desired_api(k, v or {}) for k, v in (data.get("custom_apis") or {}).items()},
        })
    return units


def source_path(path, roots):
    """Path relative to the repo root, else to the input folder: never machine-specific."""
    for root in roots:
        try:
            return path.resolve().relative_to(root).as_posix()
        except ValueError:
            continue
    return path.name


def execution_key(step):
    """Dataverse order within one (table, message): stage, sync before async, then rank."""
    return (STAGE_ORDER[step["stage"]], step["mode"] != "sync", step["rank"], step["name"].lower())


def pipelines(units, tables_filter=None):
    """{(table, message): [step + unit info]} sorted by table, message, execution order."""
    groups = {}
    for u in units:
        for s in u["steps"]:
            if tables_filter is not None and (s["table"] or "") not in tables_filter:
                continue
            groups.setdefault((s["table"] or "", s["message"].lower()), []).append(
                dict(s, unit=u["name"], file=u["file"]))
    return {k: sorted(v, key=execution_key) for k, v in sorted(groups.items())}


def custom_apis(units, tables_filter=None):
    apis = {}
    for u in units:
        for name, api in u["custom_apis"].items():
            if tables_filter is not None and (api["bound_table"] or "") not in tables_filter:
                continue
            apis[name.lower()] = dict(api, unit=u["name"], file=u["file"])
    return [apis[k] for k in sorted(apis)]


def same_rank(steps):
    """Sync steps sharing stage and rank: Dataverse does not guarantee their order."""
    seen = {}
    for s in steps:
        if s["mode"] == "sync":
            seen.setdefault((s["stage"], s["rank"]), []).append(s["name"])
    return [names for names in seen.values() if len(names) > 1]


# --------------------------------------------------------------------------- #
# Rendering helpers
# --------------------------------------------------------------------------- #
def label(s):
    """Mermaid node label: quoted, with the quote escaped."""
    return '"' + str(s).replace('"', "#quot;") + '"'


def cell(v):
    """Markdown table cell."""
    if v is None or v == "" or v == []:
        return "—"
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, list):
        v = ", ".join(f"`{x}`" for x in v)
    return " ".join(str(v).replace("|", "\\|").split())


def short(typename):
    return typename.rsplit(".", 1)[-1]


def table_md(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    out += ["| " + " | ".join(cell(c) for c in r) + " |" for r in rows]
    return out


# --------------------------------------------------------------------------- #
# Execution pipeline
# --------------------------------------------------------------------------- #
def pipeline_diagram(steps, main_label):
    lines = ["flowchart LR"]
    blocks = []  # subgraph ids in execution order, around the main operation
    disabled = []
    by_block = {}
    for s in steps:
        block = s["stage"] if s["mode"] == "sync" else "async"
        by_block.setdefault(block, []).append(s)
    n = 0
    for block, title in (("pre-validation", "Pre-validation"), ("pre-operation", "Pre-operation"),
                         ("main", None), ("post-operation", "Post-operation"),
                         ("async", "Post-operation · async")):
        if block == "main":
            lines.append(f"    core([{label(main_label)}])")
            blocks.append("core")
            continue
        if block not in by_block:
            continue
        gid = "stage_" + block.replace("-", "_")
        lines.append(f"    subgraph {gid}[{label(title)}]")
        previous = None
        for s in by_block[block]:
            n += 1
            text = f"{short(s['plugin'])}<br/>rank {s['rank']}"
            if not s["enabled"]:
                text += " · disabled"
                disabled.append(f"s{n}")
            lines.append(f"        s{n}[{label(text)}]")
            # An arrow only where Dataverse guarantees the order: a higher rank among sync
            # steps. Same rank: a dotted line. Async steps: no order at all.
            if previous is not None and block != "async":
                link = "-.-" if s["rank"] == previous["rank"] else "-->"
                lines.append(f"        s{n - 1} {link} s{n}")
            previous = s
        lines.append("    end")
        blocks.append(gid)
    lines.append("    " + " --> ".join(blocks))
    if disabled:
        lines.append("    classDef disabled stroke-dasharray: 5 5,opacity:0.6")
        lines.append(f"    class {','.join(disabled)} disabled")
    return lines


def render_pipelines(units, apis_by_name, tables_filter):
    out = ["## Execution pipeline", ""]
    groups = pipelines(units, tables_filter)
    if not groups:
        return out + ["No step is registered.", ""]
    out += ["Steps in the order Dataverse runs them for each table and message: stage, sync before "
            "async, then rank. An arrow is a guaranteed order; a dotted line joins sync steps of the "
            "same rank, whose order is not guaranteed. Async steps run after the operation, in no "
            "guaranteed order.", ""]
    for (table, message), steps in groups.items():
        out += [f"### {steps[0]['message']} · {table or NO_TABLE}", ""]
        api = apis_by_name.get(message)
        main = f"Main operation: {short(api['plugin'])}" if api and api.get("plugin") else "Main operation"
        out += ["```mermaid"] + pipeline_diagram(steps, main) + ["```", ""]
        rows = []
        for i, s in enumerate(steps, 1):
            images = [f"{im['name']} ({im['type']}: {', '.join(im['attributes']) or 'all columns'})"
                      for im in s["images"].values()]
            rows.append([i, STAGE_TITLE[s["stage"]], s["mode"], s["rank"], s["name"], f"`{s['plugin']}`",
                         s["filtering_attributes"] or None, "; ".join(images) or None,
                         s["enabled"], s.get("description")])
        out += table_md(["#", "Stage", "Mode", "Rank", "Step", "Plug-in", "Filtering attributes",
                         "Images", "Enabled", "Description"], rows)
        out.append("")
        for names in same_rank(steps):
            out += [f"> Same stage and rank — Dataverse does not guarantee the order of: "
                    + ", ".join(f"`{n}`" for n in names) + ".", ""]
    return out


# --------------------------------------------------------------------------- #
# Custom APIs
# --------------------------------------------------------------------------- #
def apis_diagram(apis):
    lines = ["flowchart LR"]
    tables, classes = {}, {}
    for i, a in enumerate(apis, 1):
        lines.append(f"    a{i}{{{{{label(a['uniquename'])}}}}}")
        if a["bound_table"]:
            tid = tables.setdefault(a["bound_table"], f"t{len(tables) + 1}")
            arrow = "-- collection -->" if a["binding"] == "entity-collection" else "-->"
            lines.append(f"    {tid}[({label(a['bound_table'])})] {arrow} a{i}")
        if a.get("plugin"):
            cid = classes.setdefault(a["plugin"], f"c{len(classes) + 1}")
            lines.append(f"    a{i} --> {cid}[{label(a['plugin'])}]")
    return lines


def param_rows(params, request):
    rows = []
    for p in sorted(params.values(), key=lambda p: p["uniquename"].lower()):
        row = [f"`{p['uniquename']}`", p["type"], p["table"]]
        if request:
            row.append(p["optional"])
        rows.append(row + [p.get("display_name"), p.get("description")])
    return rows


def render_apis(apis):
    out = ["## Custom APIs", ""]
    if not apis:
        return out + ["No Custom API is described.", ""]
    out += ["```mermaid"] + apis_diagram(apis) + ["```", ""]
    for a in apis:
        out += [f"### {a['uniquename']}", ""]
        if a.get("description"):
            out += [" ".join(a["description"].split()), ""]
        binding = a["binding"] + (f" (`{a['bound_table']}`)" if a["bound_table"] else "")
        props = [["Display name", a["display_name"]], ["Kind", "function" if a["is_function"] else "action"],
                 ["Binding", binding], ["Plug-in", f"`{a['plugin']}`" if a.get("plugin") else None],
                 ["Allowed custom steps", a["allowed_steps"]], ["Workflow enabled", a["workflow_enabled"]],
                 ["Private", a["is_private"]], ["Execute privilege", a.get("execute_privilege")],
                 ["Source", f"`{a['file']}`"]]
        out += table_md(["Property", "Value"], props) + [""]
        if a["request"]:
            out += ["Request parameters:", ""]
            out += table_md(["Name", "Type", "Table", "Optional", "Display name", "Description"],
                            param_rows(a["request"], True)) + [""]
        if a["response"]:
            out += ["Response properties:", ""]
            out += table_md(["Name", "Type", "Table", "Display name", "Description"],
                            param_rows(a["response"], False)) + [""]
    return out


def render(units, tables_filter=None):
    wanted = {t.lower() for t in tables_filter} if tables_filter else None
    apis = custom_apis(units, wanted)
    all_apis = {a["uniquename"].lower(): a for a in custom_apis(units)}
    out = [GENERATED, "", "# Plug-in registrations", ""]
    out += table_md(["Source", "Kind", "Name", "Steps", "Custom APIs"],
                    [[f"`{u['file']}`", u["kind"], u["name"], len(u["steps"]), len(u["custom_apis"])]
                     for u in units]) + [""]
    out += render_pipelines(units, all_apis, wanted)
    out += render_apis(apis)
    return "\n".join(out).rstrip("\n") + "\n"


# --------------------------------------------------------------------------- #
# CLI
# --------------------------------------------------------------------------- #
def write_or_check(content, out, check):
    """Shared by the documentation tools: print, write, or compare with the file."""
    if check:
        if not out:
            raise SystemExit("ERROR: --check needs --out <file>")
        path = Path(out)
        if not path.is_file() or path.read_text(encoding="utf-8") != content:
            print(f"STALE: {out} differs from the model — regenerate it", file=sys.stderr)
            return 1
        print(f"Up to date: {out}")
        return 0
    if out:
        path = Path(out)
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(content)
        print(f"Written: {out}")
    else:
        sys.stdout.write(content)
    return 0


def _csv(value):
    return [v.strip() for v in value.split(",") if v.strip()] if value else None


def cmd_doc(args):
    units = load_units(args.path)
    return write_or_check(render(units, _csv(args.tables)), args.out, args.check)


def main(argv=None):
    ap = argparse.ArgumentParser(prog="dv_plugin_docs.py", description=__doc__.split("\n\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("doc", help="execution pipeline and Custom APIs of the plug-in model")
    p.add_argument("path", help="a *.dv.plugin.yaml file, or a folder searched recursively")
    p.add_argument("--out", help="write to this file instead of stdout")
    p.add_argument("--check", action="store_true", help="compare with --out instead of writing (CI)")
    p.add_argument("--tables", help="comma-separated table logical names to include (default: all)")
    args = ap.parse_args(argv)
    return {"doc": cmd_doc}[args.cmd](args)


if __name__ == "__main__":
    sys.exit(main())
