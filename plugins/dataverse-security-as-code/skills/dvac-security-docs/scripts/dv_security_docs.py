#!/usr/bin/env python3
"""
dv_security_docs.py — functional documentation of the Dataverse security roles
==============================================================================

Generates a Markdown document with Mermaid diagrams from the security model
(``_meta.dv.security.yaml`` + ``roles/*.dv.security.yaml``, see the dvac-security
skill)::

    doc <path> [--out <file>] [--check] [--roles <a,b>] [--tables <a,b>]

The document has three parts:

    Roles            a summary table of the roles and the access level legend.
    Access by table  one matrix: tables × roles, each cell the verbs grouped by
                     access level — who can do what on each table.
    Role details     per role: a diagram role → access level (scope) → verbs →
                     tables, the role-editor grid and the other privileges.

Offline and read-only: reads the model files only, never the environment. The
model is validated first (the dvac-security validator); an invalid model is
refused. The output is deterministic — same model, same bytes — so the file can
be committed and checked in CI with ``--check``.

Exit codes:
    0  success (or --check: the file is up to date)
    1  error, invalid model, or --check: the file is missing or stale

Do not edit this script per project — edit the model files.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

SKILL_DIR = Path(__file__).resolve().parent.parent
# The model loader and validator belong to the sibling skill of the same plugin.
sys.path.insert(0, str(SKILL_DIR.parent / "dvac-security" / "scripts"))
import dv_security as dvs  # noqa: E402

GENERATED = "<!-- Generated by dv_security_docs.py from the *.dv.security.yaml files. Do not edit by hand. -->"

VERBS = ("create", "read", "write", "delete", "append", "append_to", "assign", "share")
VERB_TITLE = {"create": "Create", "read": "Read", "write": "Write", "delete": "Delete", "append": "Append",
              "append_to": "Append to", "assign": "Assign", "share": "Share"}
# Widest scope first: the order a reader scans "who sees what".
LEVELS = ("organization", "parent_child", "business_unit", "user")
LEVEL_GLYPH = {"user": "⚪", "business_unit": "🔵", "parent_child": "🔴", "organization": "🟢"}
NO_ACCESS = "-"
LEVEL_TITLE = {"user": "User", "business_unit": "Business unit", "parent_child": "Parent: child business units",
               "organization": "Organization"}
# Platform meaning of each access level (PrivilegeDepth Basic / Local / Deep / Global).
LEVEL_SCOPE = {
    "user": "records the user owns, records shared with them, and records owned by or shared with their teams",
    "business_unit": "records in the user's business unit",
    "parent_child": "records in the user's business unit and every business unit below it",
    "organization": "all records, whatever their business unit",
}
LEVEL_SHORT = {"user": "Own records", "business_unit": "Their business unit",
               "parent_child": "Their business unit and child units", "organization": "All records"}
# Mermaid fills, with an explicit dark text colour so they stay legible in dark themes.
# Same colours as the level emoji.
LEVEL_STYLE = {"organization": "fill:#2e7d32,stroke:#1b5e20,color:#ffffff",
               "parent_child": "fill:#c62828,stroke:#8e0000,color:#ffffff",
               "business_unit": "fill:#1565c0,stroke:#0d47a1,color:#ffffff",
               "user": "fill:#ffffff,stroke:#616161,color:#000000"}
INHERITANCE = {"team_only": "Team privileges only",
               "direct_and_team": "Direct user (Basic) access level and team privileges"}


# --------------------------------------------------------------------------- #
# Model
# --------------------------------------------------------------------------- #
def load_roles(path_arg):
    """(model dir relative path, validated roles sorted by name), or SystemExit with the errors."""
    path = Path(path_arg)
    if not path.exists():
        raise SystemExit(f"ERROR: {path_arg} does not exist")
    model_dir = dvs.find_model_dir(path)
    if model_dir is None:
        raise SystemExit(f"ERROR: no {dvs.META_FILE} found at or above {path_arg} — "
                         "point to the security model folder (e.g. dataverse/security)")
    report = dvs.validate_model(model_dir)
    if report.errors:
        for e in report.errors:
            print("  ✗ " + e, file=sys.stderr)
        raise SystemExit(f"ERROR: the model is invalid ({len(report.errors)} error(s)) — "
                         "run dv_security.py validate and fix it first")
    model = dvs.load_model(model_dir)
    base = source_path(model_dir, dvs.find_repo_root(model_dir))
    roles = []
    for r in model["roles"]:
        spec = r["spec"]
        tables = {}
        for table, verbs in (spec.get("tables") or {}).items():
            tables[table.lower()] = {v: lvl for v, lvl in (verbs or {}).items() if lvl != "none"}
        roles.append({
            "name": spec["name"], "description": spec.get("description"),
            "inheritance": spec.get("member_inheritance"),
            "file": f"{base}/{r['file']}" if base else r["file"],
            "tables": dict(sorted(tables.items())),
            "privileges": {k: v for k, v in sorted((spec.get("privileges") or {}).items(),
                                                     key=lambda kv: kv[0].lower()) if v != "none"},
        })
    return sorted(roles, key=lambda r: dvs.role_key(r["name"]))


def source_path(path, root):
    """Path relative to the repo root: never machine-specific."""
    try:
        rel = path.resolve().relative_to(root.resolve()).as_posix()
    except ValueError:
        return path.name
    return "" if rel == "." else rel


def by_level(verbs):
    """{level: [verb, …]} for one table, widest level first, verbs in role-editor order."""
    out = {}
    for verb in VERBS:
        level = verbs.get(verb)
        if level:
            out.setdefault(level, []).append(verb)
    return {lvl: out[lvl] for lvl in LEVELS if lvl in out}


# --------------------------------------------------------------------------- #
# Rendering helpers
# --------------------------------------------------------------------------- #
def label(s):
    """Mermaid node label: quoted, with the quote escaped."""
    return '"' + str(s).replace('"', "#quot;") + '"'


def cell(v):
    """Markdown table cell."""
    if v is None or v == "":
        return "—"
    return " ".join(str(v).replace("|", "\\|").split())


def table_md(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    out += ["| " + " | ".join(cell(c) for c in r) + " |" for r in rows]
    return out


def verbs_text(verbs):
    return ", ".join(VERB_TITLE[v].lower() for v in verbs)


def anchor(name):
    """GitHub heading anchor of a role section."""
    keep = "".join(c for c in name.lower() if c.isalnum() or c in " -_")
    return keep.replace(" ", "-")


# --------------------------------------------------------------------------- #
# Sections
# --------------------------------------------------------------------------- #
def render_summary(roles):
    out = ["## Roles", ""]
    rows = [[f"[{r['name']}](#{anchor(r['name'])})", r["description"],
             INHERITANCE.get(r["inheritance"]) if r["inheritance"] else None,
             sum(1 for v in r["tables"].values() if v), len(r["privileges"]), f"`{r['file']}`"]
            for r in roles]
    out += table_md(["Role", "Description", "Member's privilege inheritance", "Tables", "Other privileges",
                     "Source"], rows)
    out += ["", "### Access levels", "",
            "An access level is the scope of records a privilege applies to.", ""]
    out += table_md(["Symbol", "Level", "Model value", "The user can act on"],
                    [[LEVEL_GLYPH[l], LEVEL_TITLE[l], f"`{l}`", LEVEL_SCOPE[l]] for l in LEVELS])
    out += ["", "A privilege the role doesn't hold is shown as -.", ""]
    return out


def render_matrix(roles):
    out = ["## Access by table", ""]
    tables = sorted({t for r in roles for t, v in r["tables"].items() if v})
    if not tables:
        return out + ["No table privilege is described.", ""]
    out += ["What each role can do on each table, grouped by access level (widest first).", ""]
    rows = []
    for t in tables:
        row = [f"`{t}`"]
        for r in roles:
            groups = by_level(r["tables"].get(t) or {})
            row.append("<br>".join(f"{LEVEL_GLYPH[l]} {verbs_text(vs)}" for l, vs in groups.items()) or NO_ACCESS)
        rows.append(row)
    out += table_md(["Table"] + [r["name"] for r in roles], rows)
    return out + [""]


def role_diagram(role):
    """Role → access level → one node per set of verbs, listing the tables that share it."""
    lines = ["flowchart LR", f"    role([{label(role['name'])}])"]
    groups = {lvl: {} for lvl in LEVELS}
    for table, verbs in role["tables"].items():
        for lvl, vs in by_level(verbs).items():
            groups[lvl].setdefault(tuple(vs), []).append(table)
    others = {lvl: [p for p, l in role["privileges"].items() if l == lvl] for lvl in LEVELS}
    n = 0
    used = []
    for lvl in LEVELS:
        if not groups[lvl] and not others[lvl]:
            continue
        lid = f"l_{lvl}"
        used.append(lvl)
        lines.append(f"    role --> {lid}[{label(LEVEL_GLYPH[lvl] + ' ' + LEVEL_SHORT[lvl])}]")
        for vs in sorted(groups[lvl], key=lambda vs: [VERBS.index(v) for v in vs]):
            n += 1
            text = f"<b>{verbs_text(vs)}</b><br/>" + "<br/>".join(groups[lvl][vs])
            lines.append(f"    {lid} --> n{n}[{label(text)}]")
        if others[lvl]:
            n += 1
            text = "<b>other privileges</b><br/>" + "<br/>".join(others[lvl])
            lines.append(f"    {lid} --> n{n}[{label(text)}]")
    if not used:
        lines.append(f"    role --> empty[{label('No privilege')}]")
    for lvl in used:
        lines.append(f"    classDef {lvl} {LEVEL_STYLE[lvl]}")
        lines.append(f"    class l_{lvl} {lvl}")
    return lines


def render_role(role):
    out = [f"### {role['name']}", ""]
    if role["description"]:
        out += [" ".join(role["description"].split()), ""]
    out += ["```mermaid"] + role_diagram(role) + ["```", ""]
    tables = {t: v for t, v in role["tables"].items() if v}
    if tables:
        out += ["Table privileges:", ""]
        out += table_md(["Table"] + [VERB_TITLE[v] for v in VERBS],
                        [[f"`{t}`"] + [LEVEL_GLYPH.get(v.get(verb), NO_ACCESS) for verb in VERBS]
                         for t, v in tables.items()]) + [""]
    if role["privileges"]:
        out += ["Other privileges:", ""]
        out += table_md(["Privilege", "Level"],
                        [[f"`{p}`", f"{LEVEL_GLYPH[l]} {LEVEL_TITLE[l]}"] for p, l in role["privileges"].items()])
        out += [""]
    if not tables and not role["privileges"]:
        out += ["The role holds no privilege.", ""]
    props = [["Member's privilege inheritance",
              INHERITANCE.get(role["inheritance"]) if role["inheritance"] else "not managed by the model"],
             ["Source", f"`{role['file']}`"]]
    return out + table_md(["Property", "Value"], props) + [""]


def render(roles, roles_filter=None, tables_filter=None):
    if tables_filter:
        keep = {t.lower() for t in tables_filter}
        roles = [dict(r, tables={t: v for t, v in r["tables"].items() if t in keep}) for r in roles]
    if roles_filter:
        wanted = {dvs.role_key(n) for n in roles_filter}
        unknown = sorted(wanted - {dvs.role_key(r["name"]) for r in roles})
        if unknown:
            raise SystemExit("ERROR: unknown role(s) in --roles: " + ", ".join(unknown))
        roles = [r for r in roles if dvs.role_key(r["name"]) in wanted]
    out = [GENERATED, "", "# Security roles", ""]
    if not roles:
        return "\n".join(out + ["No security role is described.", ""])
    out += render_summary(roles)
    out += render_matrix(roles)
    out += ["## Role details", ""]
    for r in roles:
        out += render_role(r)
    return "\n".join(out).rstrip("\n") + "\n"


# --------------------------------------------------------------------------- #
# CLI
# --------------------------------------------------------------------------- #
def write_or_check(content, out, check):
    """Shared by the documentation tools: print, write, or compare with the file."""
    if check:
        if not out:
            raise SystemExit("ERROR: --check needs --out <file>")
        path = Path(out)
        if not path.is_file() or path.read_text(encoding="utf-8") != content:
            print(f"STALE: {out} differs from the model — regenerate it", file=sys.stderr)
            return 1
        print(f"Up to date: {out}")
        return 0
    if out:
        path = Path(out)
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(content)
        print(f"Written: {out}")
    else:
        sys.stdout.write(content)
    return 0


def _csv(value):
    return [v.strip() for v in value.split(",") if v.strip()] if value else None


def cmd_doc(args):
    roles = load_roles(args.path)
    return write_or_check(render(roles, _csv(args.roles), _csv(args.tables)), args.out, args.check)


def main(argv=None):
    ap = argparse.ArgumentParser(prog="dv_security_docs.py", description=__doc__.split("\n\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("doc", help="functional documentation of the security roles")
    p.add_argument("path", help="the security model folder (holding _meta.dv.security.yaml) or a file in it")
    p.add_argument("--out", help="write to this file instead of stdout")
    p.add_argument("--check", action="store_true", help="compare with --out instead of writing (CI)")
    p.add_argument("--roles", help="comma-separated role names to include (default: all)")
    p.add_argument("--tables", help="comma-separated table logical names to include (default: all); "
                                    "other privileges are always shown")
    args = ap.parse_args(argv)
    dvs.ensure_deps(dvs.REQUIREMENTS)
    return {"doc": cmd_doc}[args.cmd](args)


if __name__ == "__main__":
    sys.exit(main())
